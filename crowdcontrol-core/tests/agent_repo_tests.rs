#[test]
fn test_save_and_load_agent_with_repo_slug() -> Result<()> {
    let (config, _temp_dir) = create_test_config();
    let agent_name = "myapp-main";
    let workspace_path = config.agent_workspace_path(agent_name);
    fs::create_dir_all(&workspace_path)?;

    let agent = Agent {
        name: agent_name.to_string(),
        status: AgentStatus::Created,
        container_id: None,
        repository: "git@github.com:org/myapp.git".to_string(),
        branch: Some("main".to_string()),
        created_at: Utc::now(),
        workspace_path: workspace_path.clone(),
        repo_slug: Some("myapp".to_string()),
    };

    save_agent_metadata(&config, &agent)?;

    let loaded = load_agent_metadata(&config, agent_name)?;
    assert_eq!(loaded.repo_slug, Some("myapp".to_string()));

    Ok(())
}

