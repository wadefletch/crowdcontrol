// TDD: Tests for Agent-Repo association
// Run with: cargo test --package crowdcontrol-core --test agent_repo_tests

use anyhow::Result;
use chrono::Utc;
use crowdcontrol_core::{
    agent::{load_agent_metadata, save_agent_metadata, AgentMetadata},
    Agent, AgentStatus, Config,
};
use std::fs;
use tempfile::TempDir;

fn create_test_config() -> (Config, TempDir) {
    let temp_dir = tempfile::tempdir().unwrap();
    let config = Config {
        workspaces_dir: temp_dir.path().to_path_buf(),
        image: "crowdcontrol:latest".to_string(),
        verbose: 0,
        default_memory: None,
        default_cpus: None,
    };
    (config, temp_dir)
}

#[test]
fn test_agent_has_repo_slug_field() {
    let agent = Agent {
        name: "myapp-main".to_string(),
        status: AgentStatus::Created,
        container_id: None,
        repository: "git@github.com:org/myapp.git".to_string(),
        branch: Some("main".to_string()),
        created_at: Utc::now(),
        workspace_path: "/tmp/test".into(),
        repo_slug: Some("myapp".to_string()),
    };

    assert_eq!(agent.repo_slug, Some("myapp".to_string()));
}

