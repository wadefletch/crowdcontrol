#[test]
fn test_legacy_metadata_loads_with_none_repo_slug() -> Result<()> {
    // Simulate loading metadata that was saved before repo_slug existed
    let (config, _temp_dir) = create_test_config();
    let agent_name = "legacy-agent";
    let workspace_path = config.agent_workspace_path(agent_name);
    let metadata_dir = workspace_path.join(".crowdcontrol");
    fs::create_dir_all(&metadata_dir)?;

    // Write legacy metadata JSON without repo_slug field
    let legacy_json = r#"{
        "_comment": "This file is auto-generated by CrowdControl. Do not edit manually.",
        "name": "legacy-agent",
        "repository": "git@github.com:org/legacy.git",
        "branch": "main",
        "created_at": "2024-01-01T00:00:00Z",
        "container_id": null
    }"#;

    fs::write(metadata_dir.join("metadata.json"), legacy_json)?;

    // Should load successfully with repo_slug = None
    let loaded = load_agent_metadata(&config, agent_name)?;
    assert_eq!(loaded.repo_slug, None);
    assert_eq!(loaded.repository, "git@github.com:org/legacy.git");

    Ok(())
}

